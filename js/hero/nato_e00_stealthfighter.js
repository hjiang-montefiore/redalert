/* ================= nato_e00_stealthfighter.js  -  HERO MODEL =================
   F-35A Lightning II.  Hand-built reference airframe for era e00 aircraft:
   the rest of the e00 roster is generated by air3d_era.js and will be tuned
   to match the look established here.

   Model space follows the house contract and models3d.js:
       +X nose / front,  +Y left,  +Z up,  real metres.
   render3d.js applies rotation.x = -PI/2 and renormalises by measured length,
   so what survives to the screen is the PROPORTION.

   Why this shape and not "generic modern jet":
     - ONE engine.  A single round nozzle on the centreline, not a pair.
     - A chunky mid body: the F-35 is deep because the weapons bays are inside
       it.  The belly carries two long bay bulges the width of an AMRAAM.
     - A trapezoidal wing with a plain straight leading edge.  There is NO
       leading-edge root extension spike - that is the teen-series look
       (F-16/F-18) and putting one here would date the model twenty years.
     - Canted twin fins on short aft booms either side of the nozzle.
     - Diverterless supersonic intakes: a fixed compression BUMP moulded into
       the fuselage side ahead of a forward-raked cowl lip.  No splitter plate,
       no boundary-layer gap.  This is the single most identifiable feature of
       the aeroplane after the fin cant.
     - A faceted chined forebody: a hard horizontal edge runs from the radome
       back along the fuselage side and dies into the wing leading edge.

   Colour comes from the PAINT table at the top of js/air3d_era.js: this unit
   is spec'd camo "twotone", 0x768086, modern US grey-on-grey.  Roughness and
   metalness follow the house SKIN tier rather than the parametric values.

   Three material tiers only: SKIN (textured), METAL, GLASS.
============================================================================ */
