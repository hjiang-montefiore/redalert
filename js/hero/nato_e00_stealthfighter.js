    /* ---------------------------------------------- cockpit interior ---- */
    g.add(box(THREE, P.void_, 2.05, 0.92, 0.55, 4.62, 0, 0.32));
    g.add(box(THREE, P.dark, 0.30, 0.60, 0.42, 5.42, 0, 0.52));   /* coaming */
