  function makeTextures(THREE) {
    if (texCache) return texCache;
    var f = null, p = null;
    try {
      f = new THREE.CanvasTexture(fuseCanvas());
      p = new THREE.CanvasTexture(panelCanvas());
      [f, p].forEach(function (t) {
        t.wrapS = t.wrapT = THREE.RepeatWrapping;
        if (THREE.sRGBEncoding !== undefined) t.encoding = THREE.sRGBEncoding;
        t.anisotropy = 8;
      });
    } catch (e) { f = null; p = null; }
    texCache = { fuse: f, panel: p };
    return texCache;
  }

