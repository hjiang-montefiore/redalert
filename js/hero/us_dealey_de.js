/* ============================================================================
   us_dealey_de.js -- HERO model: USS Dealey (DE-1006), lead ship of the
   Dealey class (SCB 72), the first destroyer escort the US Navy built after
   the war, as she was completed by Bath Iron Works and commissioned on 3 June
   1954 (row nato_e50_corvette).

   Her fit is her own and nobody else's in the class: the two British SQUID
   mortars side by side ahead of the bridge (Friedman, U.S. Destroyers p.274,
   via the class article; the 28 May 1954 trials photograph shows one), where
   her twelve sisters carried the Weapon Alpha launcher. With them the two
   OPEN, manually trained twin 3-inch/50 Mk 33 mounts fore and aft, each with
   its small Mk 34 dish of the Mk 63 fire control, the SPS-6 air search on a
   four-legged lattice mast, one short raked stack with a black hood, two
   motor whaleboats in curved davits, and on the fantail the depth-charge
   throwers and the stern racks. No DASH: she is one of the three ships that
   never received the hangar and flight deck (they came in the 1960s and
   replaced the after gun on the others), and no Mk 32 tubes (late 1960s).

   References (Wikimedia Commons; there is no scale drawing of the class on
   Commons, so the shapes rest on near-orthogonal photographs and the
   published dimensions, as the brief allows):
     p1  Dealey on trials, 28 May 1954, starboard bow from above (the fit)
     p2  Dealey off South America c.1959, port bow
     p3  Bridget (DE-1024) c.1960, starboard bow from above
     p4  Hartley (DE-1029), 1 Aug 1957, port bow, almost broadside
     p5  Cromwell and Courtney in the Pedro Miguel locks c.1961, bows from
         above
     p6  Hammerberg (DE-1015) c.1957, starboard bow
     p7  Lester (DE-1022) c.1958, starboard bow from above
     p8  Bauer (DE-1025), late 1950s, starboard side from above
     p9  Hooper (DE-1026) c.1960, colour, starboard bow (the paint)
     p11 John Willis (DE-1027), early 1960s, port quarter (the after mount,
         the stern and the transom)
     p12 Courtney (DE-1021), April 1961, a true port broadside from a long
         way off: the profile every station below is measured on
   Published figures (class article; Conway's 1947-95 p.595; Friedman): 314
   ft 6 in (95.9 m) overall, 308 ft (93.9 m) on the waterline, beam 36 ft 8 in
   (11.18 m), draught 11 ft 10 in (3.6 m), 1,314 t light, 1,877 t full load,
   one shaft.

   RECOGNITION LIST (what this model must show; the reference under it):
     1. A small flush-decked hull, a high bow with a nearly upright stem and
        a strong sheer that falls to a low waist and a low fantail; a broad
        flat transom (p12, p4, p11).
     2. The forward twin 3-inch/50: an OPEN mount inside a round splinter tub
        on the forecastle, its Mk 34 dish on the mount (p1, p2).
     3. The two Squids on the low house between the gun tub and the bridge
        (p1 and its caption; class article).
     4. The bridge: a flush-sided block two decks high with the big arched
        opening in each side, the round-fronted pilot house with its row of
        round ports, the open bridge on top with the gun director (p1, p12,
        p8, p7).
     5. The four-legged lattice mast close abaft the bridge, two yards, the
        SPS-6 on a platform two thirds up and a small surface-search antenna
        and pole at the head (p1, p2, p12).
     6. The single short raked stack with its black hood, just abaft the
        mast (p7, p4, p12, p11).
     7. The long low after deckhouse, walkways each side, a 26-ft motor
        whaleboat in curved davits each side over the walkways (p1, p12,
        p11, p4).
     8. The after twin 3-inch/50, open, on a low bandstand on the main deck
        abaft the deckhouse, with the after Mk 63 director tub on the
        deckhouse end (p11, p12).
     9. The fantail: three depth-charge throwers each side and the two stern
        racks (p1, class article).
    10. 1950s haze grey over a black boot topping; dark decks (p9 colour).

   STATION TABLE (metres aft of the stem head, s; x in model space is 47.95
   - s). Freeboard at the deck edge off the Courtney broadside p12 (11.08 px
   to the metre, the waterline levelled):
       s     0    4   8.6   14  22.1  31.1  37.9  47.7   60   71   85  95.9
       fb  6.36 5.85 5.40 4.74 3.85  3.20  2.90  2.78  2.72 2.74 2.86 3.00
   Deck half-breadth (fraction of 5.59 m), off the bows-on views p5 and p1
   and the quarter view p11 (the transom is 0.85 of the beam):
       s     0    2    5    9   14   20   27   35   42  48-62  70   78   86
       hb  .02  .12  .29  .47  .64  .78  .89  .965 .995 1.0  .985 .96 .925
       s    92  95.9
       hb  .885 .855
   Stem: 0.85 m of rake from the stem head to the waterline (p12); keel
   level at -3.6 m from s 9 to s 72, rising to a transom just in the water.
   Positions read off p12: forward mount 19.6, Squid house 23.2-31.6, bridge
   front 31.6, pilot house to 37.2, arch 35.2-45.5, mast legs 35.2-41.0,
   stack 47.6 (base) to 48.4 (top), after deckhouse to 71.0, boats
   58.6-66.0, after director 70.0, after mount 75.5. Heights above the
   waterline: 02 deck 7.0, pilot house roof 8.8, stack rim 11.25 under its
   hood (p12 reads 11.6 to the hood's top), mast platforms 13.3 and 17.3,
   masthead 22.5, pole 26.

   NOT CONFIRMED, and drawn as the photographs suggest: every height above
   (one broadside of a sister, at perhaps ten per cent); the beam stations,
   which rest on oblique views; the Squid's elevation at rest and the shape
   of its frame (one dark mass in p1); the small masthead antenna (SPS-5 or
   SPS-4, not identifiable in p1); the director types on the bridge and the
   deckhouse end, drawn as the Mk 63 tubs the class article lists; the ASW
   torpedo launchers the class article mentions, which no photograph of
   Dealey shows, so they are not drawn; the size of the SQS-4 dome.

   Model space: +X bow, +Y port, +Z up, metres, waterline z = 0, keel -3.6.
   render3d.js scales by the X extent, so nothing stands past the stem or
   the transom: the forward barrels end 3.4 m inside the stem, the after
   ones inside the transom, the stern racks inboard of it.

   Paint. 1950s haze grey (5-H). The Hooper colour print p9 samples the
   sunlit hull at (195,207,208) and the shaded deckhouse side at
   (128,136,131): a slightly cool mid grey that, neutralised, is the 5-H
   level the Adams and Enterprise heroes took (#878b8f). By the house rule
   (the renderer's ACES pass lifts mid greys about 1.8x) it goes in at 0.9 of
   that: hull #7a7d81, deckhouses a shade lighter #7f8387, as the prints
   show them. Decks dark deck grey, the boot topping black, the bottom red.
   No hull number, name or flag.

   Materials (10): hull, deckhouse, shade (the same plating darker, for the
   house inside the arches), deck, dark, metal, light (life rafts), glass,
   mesh (radar screen) and team, which is exactly C.team. Every static
   part is merged into one mesh per material; the forward twin 3-inch is the
   "turret" node (row turret:true), its origin on the ring centre, the guns
   along +X, with its own three meshes; the after mount is baked.
   ASCII only -- a stray byte in a hex literal has broken this project.
============================================================================ */

