    g = box(THREE, 0.9, 1.2, 0.8, -L / 2 + 1.6, 0.4, 2.15); g.rotateZ(hd); g.translate(x0, y0, z0); B.S.add(g);
    g = box(THREE, 0.25, hw * 1.8, 1.5, L / 2 - 0.12, 0, 0.95, 0, -0.2, 0); g.rotateZ(hd); g.translate(x0, y0, z0); B.S.add(g);
