        var ex = P[i - 1][0] - P[i - 2][0], ez = P[i - 1][1] - P[i - 2][1];
        var l1 = Math.sqrt(ex * ex + ez * ez), l2 = Math.sqrt(dx * dx + dz * dz);
        if (l1 > 1e-6 && l2 > 1e-6) turn = Math.acos(Math.max(-1, Math.min(1, (ex * dx + ez * dz) / (l1 * l2))));
